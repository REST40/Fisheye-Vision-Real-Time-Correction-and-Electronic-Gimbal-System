#!/usr/bin/env python3
"""Generate immutable slicing-by-8 tables for the existing reflected IEEE CRC-32."""
from pathlib import Path


def render():
    tables = [[]]
    for value in range(256):
        crc = value
        for _ in range(8):
            crc = (crc >> 1) ^ (0xEDB88320 if crc & 1 else 0)
        tables[0].append(crc)
    for _ in range(7):
        tables.append([(crc >> 8) ^ tables[0][crc & 255] for crc in tables[-1]])
    lines = ['/* Generated by host/tools/ps/generate_crc32_tables.py; IEEE, not CRC-32C. */',
             '#ifndef FPTZ_CRC32_TABLES_H', '#define FPTZ_CRC32_TABLES_H',
             '#include <stdint.h>',
             '_Alignas(64) static const uint32_t fptz_crc32_tables[8][256] = {']
    for table in tables:
        lines.append('    {')
        for offset in range(0, 256, 8):
            lines.append('        ' + ', '.join(f'0x{x:08x}u' for x in table[offset:offset+8]) + ',')
        lines.append('    },')
    return '\n'.join(lines + ['};', '#endif', ''])


if __name__ == '__main__':
    destination = Path(__file__).resolve().parents[3] / 'PS/7ev_fish_app/src/fptz_crc32_tables.h'
    destination.write_text(render())
    print(destination)
