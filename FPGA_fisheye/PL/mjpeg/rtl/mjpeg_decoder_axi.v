// 标准 AXI 接口包装：PS 控制寄存器，PL 直接读写低地址 DDR。
module mjpeg_decoder_axi (
    (* X_INTERFACE_PARAMETER = "ASSOCIATED_BUSIF s_axi:m_axi, ASSOCIATED_RESET aresetn" *)
    input wire aclk,

    input wire aresetn,

    input  wire          s_axi_awvalid,
    input  wire [31:0]   s_axi_awaddr,
    input  wire          s_axi_wvalid,
    input  wire [31:0]   s_axi_wdata,
    input  wire [3:0]    s_axi_wstrb,
    input  wire          s_axi_bready,
    input  wire          s_axi_arvalid,
    input  wire [31:0]   s_axi_araddr,
    input  wire          s_axi_rready,
    output wire          s_axi_awready,
    output wire          s_axi_wready,
    output wire          s_axi_bvalid,
    output wire [1:0]    s_axi_bresp,
    output wire          s_axi_arready,
    output wire          s_axi_rvalid,
    output wire [31:0]   s_axi_rdata,
    output wire [1:0]    s_axi_rresp,

    input  wire          m_axi_awready,
    input  wire          m_axi_wready,
    input  wire          m_axi_bvalid,
    input  wire [1:0]    m_axi_bresp,
    input  wire [3:0]    m_axi_bid,
    input  wire          m_axi_arready,
    input  wire          m_axi_rvalid,
    input  wire [31:0]   m_axi_rdata,
    input  wire [1:0]    m_axi_rresp,
    input  wire [3:0]    m_axi_rid,
    input  wire          m_axi_rlast,
    output wire          m_axi_awvalid,
    (* X_INTERFACE_PARAMETER = "XIL_INTERFACENAME m_axi, NUM_READ_OUTSTANDING 2, NUM_WRITE_OUTSTANDING 8, MAX_BURST_LENGTH 8" *) // 两路使用同一RTL，每路独立额度
    output wire [31:0]   m_axi_awaddr,
    output wire [3:0]    m_axi_awid,
    output wire [7:0]    m_axi_awlen,
    output wire [1:0]    m_axi_awburst,
    output wire          m_axi_wvalid,
    output wire [31:0]   m_axi_wdata,
    output wire [3:0]    m_axi_wstrb,
    output wire          m_axi_wlast,
    output wire          m_axi_bready,
    output wire          m_axi_arvalid,
    output wire [31:0]   m_axi_araddr,
    output wire [3:0]    m_axi_arid,
    output wire [7:0]    m_axi_arlen,
    output wire [1:0]    m_axi_arburst,
    output wire          m_axi_rready,
    output wire [2:0]    m_axi_awsize,
    output wire [2:0]    m_axi_arsize,

    output wire [31:0]   progress_dst_base,
    output wire [10:0]   progress_rows_committed,
    output wire [7:0]    progress_generation,
    output wire          progress_active,
    output wire          progress_done,
    output wire          progress_error
);
    assign m_axi_awsize = 3'd2;
    assign m_axi_arsize = 3'd2;
    jpeg_decoder decoder (
        .clk_i(aclk), .rst_i(!aresetn),
        .cfg_awvalid_i(s_axi_awvalid),
        .cfg_awaddr_i(s_axi_awaddr),
        .cfg_wvalid_i(s_axi_wvalid),
        .cfg_wdata_i(s_axi_wdata),
        .cfg_wstrb_i(s_axi_wstrb),
        .cfg_bready_i(s_axi_bready),
        .cfg_arvalid_i(s_axi_arvalid),
        .cfg_araddr_i(s_axi_araddr),
        .cfg_rready_i(s_axi_rready),
        .cfg_awready_o(s_axi_awready),
        .cfg_wready_o(s_axi_wready),
        .cfg_bvalid_o(s_axi_bvalid),
        .cfg_bresp_o(s_axi_bresp),
        .cfg_arready_o(s_axi_arready),
        .cfg_rvalid_o(s_axi_rvalid),
        .cfg_rdata_o(s_axi_rdata),
        .cfg_rresp_o(s_axi_rresp),
        .outport_awready_i(m_axi_awready),
        .outport_wready_i(m_axi_wready),
        .outport_bvalid_i(m_axi_bvalid),
        .outport_bresp_i(m_axi_bresp),
        .outport_bid_i(m_axi_bid),
        .outport_arready_i(m_axi_arready),
        .outport_rvalid_i(m_axi_rvalid),
        .outport_rdata_i(m_axi_rdata),
        .outport_rresp_i(m_axi_rresp),
        .outport_rid_i(m_axi_rid),
        .outport_rlast_i(m_axi_rlast),
        .outport_awvalid_o(m_axi_awvalid),
        .outport_awaddr_o(m_axi_awaddr),
        .outport_awid_o(m_axi_awid),
        .outport_awlen_o(m_axi_awlen),
        .outport_awburst_o(m_axi_awburst),
        .outport_wvalid_o(m_axi_wvalid),
        .outport_wdata_o(m_axi_wdata),
        .outport_wstrb_o(m_axi_wstrb),
        .outport_wlast_o(m_axi_wlast),
        .outport_bready_o(m_axi_bready),
        .outport_arvalid_o(m_axi_arvalid),
        .outport_araddr_o(m_axi_araddr),
        .outport_arid_o(m_axi_arid),
        .outport_arlen_o(m_axi_arlen),
        .outport_arburst_o(m_axi_arburst),
        .outport_rready_o(m_axi_rready),
        .progress_dst_base_o(progress_dst_base),
        .progress_rows_committed_o(progress_rows_committed),
        .progress_generation_o(progress_generation),
        .progress_active_o(progress_active),
        .progress_done_o(progress_done),
        .progress_error_o(progress_error)
    );
endmodule
